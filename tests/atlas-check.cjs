// Focused Atlas check; no API calls, database or browser suite.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const atlas=require('../atlas.js');
const zip=require('../vendor/fflate.min.js');
for(const name of ['atlas.js','atlas-map.js','app-i18n.js','sw.js'])new vm.Script(fs.readFileSync(path.join(root,name),'utf8'),{filename:name});
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
for(const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g))if(!/\bsrc=/.test(match[1])&&match[2].trim())new vm.Script(match[2],{filename:'index.html inline'});

const photo=(id,rating,n,lat,bird='A',captureTime='2025-01-01T00:00:00Z')=>({id,averageSurveyRating:rating,surveyRatingCount:n,lat,lon:20,bird,captureTime,filename:'photo.jpg',imageUrl:'SECRET_SIGNED_URL'});
assert.equal(atlas.canUseAtlas(null,null),false);
assert.equal(atlas.canUseAtlas({id:'regular',restrictedContributor:false},null),true);
assert.equal(atlas.canUseAtlas({id:'restricted',restrictedContributor:true},null),false);
assert.equal(atlas.canUseAtlas({id:'restricted',restrictedContributor:true},{bestPicturesUnlocked:false}),false);
assert.equal(atlas.canUseAtlas({id:'restricted',restrictedContributor:true},{bestPicturesUnlocked:true}),true);
assert.equal(atlas.canUseAtlas({id:'regular'},{bestPicturesUnlocked:false}),false,'use the same authoritative profile flag as Photo Safe');
assert.equal(atlas.canUseAtlas({id:'regular',mustChangePassword:true},{bestPicturesUnlocked:true}),false);
const rows=[photo('a',4.9,10,10),photo('b',4.8,30,50),photo('c',4.8,20,70),photo('d',5,9,80),photo('e',3.9,20,90)];
assert.deepEqual(atlas.select(rows,{count:2}).map(p=>p.id),['b','a'],'quality selection must precede geographic order');
assert.deepEqual(atlas.select(rows,{count:10,order:'rating'}).map(p=>p.id),['a','b','c']);
assert.equal(atlas.select(rows,{count:10,cap:1}).length,1);
const missing=photo('missing',5,20,null,'B'),dated=photo('dated',4.7,15,-20,'C','2024-01-01T00:00:00Z');
assert.equal(atlas.order([...rows,missing],'north').at(-1).id,'missing');
assert.equal(atlas.order([rows[0],dated],'oldest')[0].id,'dated');
assert.equal(atlas.order([rows[0],dated],'newest')[0].id,'a');
assert.equal(atlas.order([rows[0],dated],'south')[0].id,'dated');
assert.equal(atlas.order([dated,rows[0]],'bird')[0].id,'a');
assert.deepEqual(atlas.order(rows,'rating'),atlas.order([...rows].reverse(),'rating'),'stable deterministic ties');
assert.equal(atlas.select(Array.from({length:205},(_,i)=>photo(String(i),4.8,20,i%90)),{count:150}).length,150);
assert.deepEqual(atlas.uniqueNames([rows[0],rows[0]]),['4.9_photo.jpg','4.9_photo_2.jpg']);
assert.ok(atlas.manifest([rows[0],rows[0]]).includes('4.9_photo_2.jpg.map.png'),'map filenames preserve photo collision suffixes');

const snapshot={criteria:atlas.settings(),createdAt:new Date().toISOString(),photos:[rows[1],rows[0]]};
const encoded=atlas.encodeLink(snapshot,'2099-01-01T00:00:00Z'),decoded=atlas.decodeLink(encoded);
assert.deepEqual(decoded.photos.map(p=>p.id),['b','a']);
assert.ok(!JSON.stringify(decoded).includes('SECRET'));
assert.throws(()=>atlas.decodeLink(encoded,Date.parse('2100-01-01')));
const jpeg=Uint8Array.from(Buffer.from('/9j/4AAQSkZJRgABAQAAAQABAAD/2wBDAP//////////////////////////////////////////////////////////////////////////////////////2wBDAf//////////////////////////////////////////////////////////////////////////////////////wAARCAABAAEDASIAAhEBAxEB/8QAFQABAQAAAAAAAAAAAAAAAAAAAAX/xAAUEAEAAAAAAAAAAAAAAAAAAAAA/9oADAMBAAIQAxAAAAF//8QAFBABAAAAAAAAAAAAAAAAAAAAAP/aAAgBAQABBQJ//8QAFBEBAAAAAAAAAAAAAAAAAAAAAP/aAAgBAwEBPwF//8QAFBEBAAAAAAAAAAAAAAAAAAAAAP/aAAgBAgEBPwF//8QAFBABAAAAAAAAAAAAAAAAAAAAAP/aAAgBAQAGPwJ//8QAFBABAAAAAAAAAAAAAAAAAAAAAP/aAAgBAQABPyF//9oADAMBAAIAAwAAABD/xAAUEQEAAAAAAAAAAAAAAAAAAAAA/9oACAEDAQE/EF//xAAUEQEAAAAAAAAAAAAAAAAAAAAA/9oACAECAQE/EF//xAAUEAEAAAAAAAAAAAAAAAAAAAAA/9oACAEBAAE/EF//2Q==','base64'));
const image={width:1,height:1,bytes:jpeg};
const parts=atlas.docxParts([{heading:'Atlas 1 / 1',photo:image,map:image,lines:['Bocian & GPS <20>','Uwagi: żółć']}],{title:'Atlas',subtitle:'Ankiety',cover:true,coverLines:['1 photo'],source:'Project GPS'});
const packed=zip.zipSync(Object.fromEntries(Object.entries(parts).map(([key,value])=>[key,typeof value==='string'?zip.strToU8(value):value])),{level:0});
const unpacked=zip.unzipSync(packed),document=zip.strFromU8(unpacked['word/document.xml']);
assert.ok(document.includes('w:orient="landscape"'));
assert.ok(document.includes('Bocian &amp; GPS &lt;20&gt;'));
assert.ok(document.includes('żółć'));
assert.equal(Object.keys(unpacked).filter(k=>k.startsWith('word/media/')).length,2);
assert.ok(!document.includes('SECRET'));
const archive=zip.unzipSync(zip.zipSync({'4.9_photo.jpg':jpeg,'atlas_manifest.csv':zip.strToU8(atlas.manifest([rows[0]]))}));
assert.deepEqual(archive['4.9_photo.jpg'],jpeg);
assert.ok(zip.strFromU8(archive['atlas_manifest.csv']).includes('surveyRatingCount'));
assert.ok(html.includes('data-app-nav="atlas"'));
assert.ok(html.includes('openPhotoCollection("atlas",null,{payload:{photos:snapshot.photos}})'));
assert.ok(html.includes('collection==="atlas"?options.payload:'));
assert.ok(html.includes('[data-app-nav="rated"],[data-app-nav="atlas"]'));
assert.ok(html.includes('atlas.openMaps(collectionSequenceIndex)'));
assert.ok(fs.readFileSync(path.join(root,'sw.js'),'utf8').includes('if(event.request.mode==="navigate")return;'));
console.log('PASS: syntax, quality-first selection, six orders, >100 photos, limits, missing GPS, link snapshot/expiry, ZIP and embedded DOCX package, shared viewer integration.');
// Optional artifact for a single XML-package validation with the platform XML parser.
if(process.argv[2])fs.writeFileSync(process.argv[2],packed);
